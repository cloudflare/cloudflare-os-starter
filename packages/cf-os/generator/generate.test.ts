// generate.ts: the committed API files are what it writes from the pin, and its write, check and
// report behaviour, against scratch package directories under the OS temp directory.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { COMMANDS_PATH, commandEntries, type Schema, SCHEMA_PATH } from "./emit.ts";
import { extractSchema } from "./extract.ts";
import { API_SOURCE, generateApi } from "./generate.ts";

const SCRIPT = join(import.meta.dirname, "generate.ts");
const FIXTURE_SCHEMA = join(import.meta.dirname, "__fixtures__", "generated", "schema.json");

function fixture(): Schema {
  return JSON.parse(readFileSync(FIXTURE_SCHEMA, "utf8")) as Schema;
}

function scratch(t: { after: (fn: () => void) => void }): string {
  const dir = mkdtempSync(join(tmpdir(), "cf-os-generate-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
}

test("the committed API files are what generate would write from the pinned api.ts", () => {
  const result = generateApi({ check: true, schema: extractSchema(API_SOURCE) });
  assert.deepEqual(result, { files: [], commands: { added: [], removed: [], changed: [] } });
});

test("writes both files, reports every command as added the first time, and nothing the second", (t) => {
  const dir = scratch(t);
  t.mock.method(console, "error", () => {});
  const first = generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  assert.deepEqual(first.files, [SCHEMA_PATH, COMMANDS_PATH]);
  assert.deepEqual(first.commands.added, [...commandEntries(fixture()).values()].map((e) => e.path).toSorted());
  assert.ok(first.commands.added.includes("open-notebook subscribe"));
  assert.equal(readFileSync(join(dir, SCHEMA_PATH), "utf8"), readFileSync(FIXTURE_SCHEMA, "utf8"));
  assert.match(readFileSync(join(dir, COMMANDS_PATH), "utf8"), /^\/\/ Generated by/);

  const second = generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  assert.deepEqual(second, { files: [], commands: { added: [], removed: [], changed: [] } });
});

test("with check, lists what is stale and writes nothing", (t) => {
  const dir = scratch(t);
  t.mock.method(console, "error", () => {});
  generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  const before = readFileSync(join(dir, COMMANDS_PATH), "utf8");
  const schema = fixture();
  schema.services.Notebook!.methods = schema.services.Notebook!.methods.filter((m) => m.name !== "lock");

  const result = generateApi({ check: true, schema, packageDir: dir, root: dir });
  assert.deepEqual(result.files, [SCHEMA_PATH, COMMANDS_PATH]);
  assert.deepEqual(result.commands, { added: [], removed: ["open-notebook lock"], changed: [] });
  assert.equal(readFileSync(join(dir, COMMANDS_PATH), "utf8"), before);
  assert.equal(readFileSync(join(dir, SCHEMA_PATH), "utf8"), readFileSync(FIXTURE_SCHEMA, "utf8"));
});

test("counts every command as added when the committed schema is unreadable, saying so", (t) => {
  const dir = scratch(t);
  const errors = t.mock.method(console, "error", () => {});
  mkdirSync(join(dir, "src", "api", "generated"), { recursive: true });
  writeFileSync(join(dir, SCHEMA_PATH), "{ not json");
  const result = generateApi({ check: true, schema: fixture(), packageDir: dir, root: dir });
  assert.equal(result.commands.added.length, commandEntries(fixture()).size);
  assert.ok(errors.mock.calls.some((call) => /unreadable/.test(String(call.arguments[0]))));
  assert.ok(!existsSync(join(dir, COMMANDS_PATH)));
});

test("the script: JSON on stdout, --check passing while fresh, usage on a bad argument", () => {
  const check = spawnSync(process.execPath, [SCRIPT, "--check"], { encoding: "utf8" });
  assert.equal(check.status, 0, check.stderr);
  assert.deepEqual(JSON.parse(check.stdout), { files: [], commands: { added: [], removed: [], changed: [] } });

  const bad = spawnSync(process.execPath, [SCRIPT, "--chek"], { encoding: "utf8" });
  assert.equal(bad.status, 1);
  assert.equal(bad.stdout, "");
  assert.match(bad.stderr, /unknown argument --chek\nUsage: node packages\/cf-os\/generator\/generate\.ts \[--check\]/);
});
