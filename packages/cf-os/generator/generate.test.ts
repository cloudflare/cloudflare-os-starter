// generate.ts: the committed API files are what it writes from the pin's schema, the schemas it
// refuses, and its write, check and report behaviour, against scratch package directories under the
// OS temp directory.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { pathToFileURL } from "node:url";
import { COMMANDS_PATH, commandEntries, type Schema, SCHEMA_FORMAT, SCHEMA_PATH } from "./emit.ts";
import { AGENT_DECLARATIONS, AGENT_FRAGMENTS, AGENT_TYPES_PATH, generateApi, renderAgentTypes, SCHEMA_SOURCE } from "./generate.ts";

const SCRIPT = join(import.meta.dirname, "generate.ts");
const FIXTURE_SCHEMA = join(import.meta.dirname, "__fixtures__", "generated", "schema.json");

/** The fixture, in the format from before upstream's schema. */
function fixture(): Schema {
  return JSON.parse(readFileSync(FIXTURE_SCHEMA, "utf8")) as Schema;
}

/** The fixture in upstream's format, which adds `format`, `direction` and streams' `element`. */
function upgraded(): Schema {
  const schema = JSON.parse(JSON.stringify(fixture()), (_key, value) =>
    value?.kind === "readableStream" ? { ...value, element: { kind: "bytes" } } : value) as Schema;
  for (const service of Object.values(schema.services)) service.direction = "server";
  return { format: SCHEMA_FORMAT, ...(schema as Omit<Schema, "format">) };
}

function scratch(t: { after: (fn: () => void) => void }): string {
  const dir = mkdtempSync(join(tmpdir(), "cf-os-generate-"));
  // Retried: a scratch git repository can still be settling when the test ends (ENOTEMPTY).
  t.after(() => rmSync(dir, { recursive: true, force: true, maxRetries: 3 }));
  return dir;
}

test("the committed API files are what generate would write from the pinned schema, which it copies verbatim", () => {
  const result = generateApi({ check: true });
  assert.deepEqual(result, { files: [], commands: { added: [], removed: [], changed: [] } });
  assert.equal(readFileSync(join(import.meta.dirname, "..", SCHEMA_PATH), "utf8"), readFileSync(SCHEMA_SOURCE, "utf8"));
});

test("agent-types.ts holds upstream's agent declarations, whole and per service, each text line for line", async (t) => {
  const agent = { declarations: "/** `a` and ${b} */\nexport interface A {\n  \"x\"(): void;\n}\n", fragments: { A: "a\n", "not-a-name": "" } };
  const dir = scratch(t);
  const path = join(dir, "agent-types.ts");
  writeFileSync(path, renderAgentTypes(agent));
  assert.match(readFileSync(path, "utf8"), /^\/\/ Generated by packages\/cf-os\/generator\/generate\.ts from .*; do not edit\. Run pnpm api:generate\.\n/);
  assert.match(readFileSync(path, "utf8"), /^ {2}"export interface A \{",$/m);
  const module = await import(pathToFileURL(path).href) as { declarations: string; fragments: Record<string, string> };
  assert.deepEqual({ declarations: module.declarations, fragments: module.fragments }, agent);
});

test("refuses a pin from before upstream's schema, and a schema in a format it does not read", (t) => {
  const dir = scratch(t);
  const source = join(dir, "workshop-api.schema.json");
  assert.throws(() => generateApi({ check: true, source, packageDir: dir, root: dir }),
    /^Error: workshop-api\.schema\.json is missing: the cloudflare-os pin predates packages\/api-schema \(cloudflare\/cloudflare-os#860\), which `cf-os api` is generated from\. Move the pin/);
  writeFileSync(source, JSON.stringify({ ...upgraded(), format: "capnweb-schema/1" }));
  assert.throws(() => generateApi({ check: true, source, packageDir: dir, root: dir }),
    /^Error: workshop-api\.schema\.json has format "capnweb-schema\/1", and this cf-os reads capnweb-schema\/0$/);
  writeFileSync(source, JSON.stringify(fixture()));
  assert.throws(() => generateApi({ check: true, source, packageDir: dir, root: dir }),
    /^Error: workshop-api\.schema\.json has no format, and this cf-os reads capnweb-schema\/0$/);
  assert.ok(!existsSync(join(dir, COMMANDS_PATH)));

  writeFileSync(source, `${JSON.stringify(upgraded(), null, 2)}\n`);
  // The agent declarations are read from beside the schema, and a pin with the one has the others.
  assert.throws(() => generateApi({ check: true, source, packageDir: dir, root: dir }),
    /^Error: workshop-api\.agent\.d\.ts is missing: the cloudflare-os pin predates packages\/api-schema/);
  for (const file of [AGENT_DECLARATIONS, AGENT_FRAGMENTS]) copyFileSync(join(SCHEMA_SOURCE, "..", file), join(dir, file));
  t.mock.method(console, "error", () => {});
  assert.deepEqual(generateApi({ check: false, source, packageDir: dir, root: dir }).files, [SCHEMA_PATH, COMMANDS_PATH, AGENT_TYPES_PATH]);
  assert.equal(readFileSync(join(dir, SCHEMA_PATH), "utf8"), readFileSync(source, "utf8"));
});

test("writes both files, reports every command as added the first time, and nothing the second", (t) => {
  const dir = scratch(t);
  t.mock.method(console, "error", () => {});
  const first = generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  assert.deepEqual(first.files, [SCHEMA_PATH, COMMANDS_PATH, AGENT_TYPES_PATH]);
  assert.deepEqual(first.commands.added, [...commandEntries(fixture()).values()].map((e) => e.path).toSorted());
  assert.ok(first.commands.added.includes("open-notebook subscribe"));
  assert.equal(readFileSync(join(dir, SCHEMA_PATH), "utf8"), readFileSync(FIXTURE_SCHEMA, "utf8"));
  assert.match(readFileSync(join(dir, COMMANDS_PATH), "utf8"), /^\/\/ Generated by/);

  const second = generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  assert.deepEqual(second, { files: [], commands: { added: [], removed: [], changed: [] } });
});

test("with check, lists what is stale and writes nothing", (t) => {
  const dir = scratch(t);
  t.mock.method(console, "error", () => {});
  generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  const before = readFileSync(join(dir, COMMANDS_PATH), "utf8");
  const schema = fixture();
  schema.services.Notebook!.methods = schema.services.Notebook!.methods.filter((m) => m.name !== "lock");

  const result = generateApi({ check: true, schema, packageDir: dir, root: dir });
  assert.deepEqual(result.files, [SCHEMA_PATH, COMMANDS_PATH]);
  assert.deepEqual(result.commands, { added: [], removed: ["open-notebook lock"], changed: [] });
  assert.equal(readFileSync(join(dir, COMMANDS_PATH), "utf8"), before);
  assert.equal(readFileSync(join(dir, SCHEMA_PATH), "utf8"), readFileSync(FIXTURE_SCHEMA, "utf8"));
});

test("counts every command as added when the committed schema is unreadable, saying so", (t) => {
  const dir = scratch(t);
  const errors = t.mock.method(console, "error", () => {});
  mkdirSync(join(dir, "src", "api", "generated"), { recursive: true });
  writeFileSync(join(dir, SCHEMA_PATH), "{ not json");
  const result = generateApi({ check: true, schema: fixture(), packageDir: dir, root: dir });
  assert.equal(result.commands.added.length, commandEntries(fixture()).size);
  assert.ok(errors.mock.calls.some((call) => /unreadable/.test(String(call.arguments[0]))));
  assert.ok(!existsSync(join(dir, COMMANDS_PATH)));
});

/** Runs git in `cwd`, as a throwaway identity, returning its stdout. */
function git(cwd: string, ...args: string[]): string {
  const result = spawnSync("git", ["-c", "user.name=test", "-c", "user.email=test@example.com", "-c", "commit.gpgsign=false", ...args],
    { cwd, encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
}

test("with since, compares the commands with that commit's schema, not the working tree's", (t) => {
  const dir = scratch(t);
  t.mock.method(console, "error", () => {});
  git(dir, "init", "-q");
  git(dir, "commit", "-q", "--allow-empty", "-m", "before cf-os api");
  const none = git(dir, "rev-parse", "HEAD");
  generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "-m", "api");
  const old = git(dir, "rev-parse", "HEAD");
  // A merge that brings the regenerated files: the working tree's schema is already the new one.
  const schema = fixture();
  schema.services.Notebook!.methods = schema.services.Notebook!.methods.filter((m) => m.name !== "lock");
  generateApi({ check: false, schema, packageDir: dir, root: dir });
  git(dir, "commit", "-q", "-am", "merge");

  assert.deepEqual(generateApi({ check: true, schema, packageDir: dir, root: dir }).commands.removed, []);
  assert.deepEqual(generateApi({ check: true, schema, packageDir: dir, root: dir, since: old }),
    { files: [], commands: { added: [], removed: ["open-notebook lock"], changed: [] } });
  // A commit from before `cf-os api` has no schema: every command is new.
  assert.equal(generateApi({ check: true, schema, packageDir: dir, root: dir, since: none }).commands.added.length,
    commandEntries(schema).size);
  assert.throws(() => generateApi({ check: true, schema, packageDir: dir, root: dir, since: "nope" }),
    /--since nope: not a commit/);
});

test("compares an old-format committed schema without the stream elements it could not record", (t) => {
  const dir = scratch(t);
  t.mock.method(console, "error", () => {});
  git(dir, "init", "-q");
  generateApi({ check: false, schema: fixture(), packageDir: dir, root: dir });
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "-m", "old format");
  const old = git(dir, "rev-parse", "HEAD");
  const none = { added: [], removed: [], changed: [] };

  // Against the working tree's schema and against the commit's, before and after the new one is written.
  assert.deepEqual(generateApi({ check: true, schema: upgraded(), packageDir: dir, root: dir }).commands, none);
  generateApi({ check: false, schema: upgraded(), packageDir: dir, root: dir });
  assert.deepEqual(generateApi({ check: true, schema: upgraded(), packageDir: dir, root: dir, since: old }).commands, none);
  // Between two schemas that both record them, a stream's element is part of the command.
  const strings = JSON.parse(JSON.stringify(upgraded()).replaceAll('"element":{"kind":"bytes"}', '"element":{"kind":"string"}')) as Schema;
  assert.deepEqual(generateApi({ check: true, schema: strings, packageDir: dir, root: dir }).commands,
    { added: [], removed: [], changed: ["import-archive", "public download"] });
});

test("the script: JSON on stdout, --check passing while fresh, usage on a bad argument", () => {
  const check = spawnSync(process.execPath, [SCRIPT, "--check"], { encoding: "utf8" });
  assert.equal(check.status, 0, check.stderr);
  assert.deepEqual(JSON.parse(check.stdout), { files: [], commands: { added: [], removed: [], changed: [] } });

  const bad = spawnSync(process.execPath, [SCRIPT, "--chek"], { encoding: "utf8" });
  assert.equal(bad.status, 1);
  assert.equal(bad.stdout, "");
  assert.match(bad.stderr, /Unknown option '--chek'.*\nUsage: node packages\/cf-os\/generator\/generate\.ts \[--check\] \[--since <commit>\]/);
});
