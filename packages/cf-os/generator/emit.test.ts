// The emitter, from the committed fixture schema (`__fixtures__/generated/schema.json`, which
// `extract.test.ts` checks) to the expected command table beside it.
//
// After changing the emitter on purpose, rewrite the expected table with
// `CF_OS_UPDATE_FIXTURES=1 node --test packages/cf-os/generator/emit.test.ts` and read the diff.

import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";
import {
  buildTable, cliDoc, COMMANDS_PATH, commandEntries, CREDENTIAL_METHODS, diffCommands, generate, kebab, ROOT_CREDENTIAL_METHODS,
  type Schema, SCHEMA_PATH, typeText,
} from "./emit.ts";

const GENERATED = join(import.meta.dirname, "__fixtures__", "generated");
const EXPECTED_COMMANDS = join(GENERATED, "commands.ts");

function fixture(): Schema {
  return JSON.parse(readFileSync(join(GENERATED, "schema.json"), "utf8")) as Schema;
}

test("renders the fixture's files as committed", () => {
  const files = generate(fixture());
  assert.deepEqual(files.map((file) => file.path), [SCHEMA_PATH, COMMANDS_PATH]);
  assert.equal(files[0]!.contents, readFileSync(join(GENERATED, "schema.json"), "utf8"));
  if (process.env.CF_OS_UPDATE_FIXTURES) writeFileSync(EXPECTED_COMMANDS, files[1]!.contents);
  assert.equal(files[1]!.contents, readFileSync(EXPECTED_COMMANDS, "utf8"));
  assert.match(files[1]!.contents, /^\/\/ Generated by packages\/cf-os\/generator\/generate\.ts from .*; do not edit\. Run pnpm api:generate\.\n/);
  assert.match(files[1]!.contents, /^import type \{ ApiTable \} from "\.\.\/table\.ts";$/m);
});

test("roots the table at authenticate()'s result, with the entry as public, less its credential methods", () => {
  const table = buildTable(fixture());
  assert.equal(table.root, "FixtureAuthedApi");
  assert.equal(table.public, "FixturePublicApi");
  assert.deepEqual(Object.keys(table.nodes.FixturePublicApi!.commands), ["download", "ping"]);
  assert.deepEqual(CREDENTIAL_METHODS, ["authenticate", "authenticateFromCfAccess", "createAccount", "login"]);
  assert.deepEqual(Object.keys(table.nodes), ["FixtureAdmin", "FixtureAuthedApi", "FixturePublicApi", "Notebook"]);
  assert.deepEqual(table.constants, { SERVICE_SALT: [1, 2, 254, 255] });

  const withPassword = buildTable(edited((schema) => {
    schema.services.FixtureAuthedApi!.methods.push({
      name: "changePassword",
      doc: "",
      params: ["oldHash", "newHash"].map((name) => ({ name, type: { kind: "bytes" }, optional: false, doc: "" })),
      returns: { kind: "void" },
    });
  }));
  assert.deepEqual(ROOT_CREDENTIAL_METHODS, ["changePassword"]);
  assert.equal(withPassword.nodes.FixtureAuthedApi!.commands["change-password"], undefined);
});

