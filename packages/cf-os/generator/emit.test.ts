test("encodes each parameter by its type", () => {
  const { nodes } = buildTable(fixture());
  const arg = (node: string, command: string, i = 0) => nodes[node]!.commands[command]!.args[i]!;
  assert.deepEqual(arg("FixtureAuthedApi", "set-mood").choices, ["busy", "calm"]);
  assert.equal(arg("FixtureAuthedApi", "set-mood").encoding, "string");
  assert.equal(arg("FixtureAuthedApi", "set-nickname").nullable, true);
  assert.equal(arg("FixtureAuthedApi", "set-nickname").encoding, "string");
  assert.equal(arg("FixtureAuthedApi", "import-archive").encoding, "stream");
  assert.equal(arg("Notebook", "upload").encoding, "bytes");
  assert.equal(arg("Notebook", "upload", 1).encoding, "boolean");
  assert.deepEqual(arg("Notebook", "file"), {
    name: "note", index: 0, encoding: "json", shape: { kind: "ref", name: "Note" }, type: "Note", doc: "",
  });
  assert.equal(arg("Notebook", "file", 1).encoding, "json");
  assert.equal(arg("Notebook", "subscribe", 1).encoding, "date");
  assert.deepEqual(arg("Notebook", "subscribe"), {
    name: "subscriber", index: 0, encoding: "callback", callback: "NotesSubscriber",
    type: "RpcStub<NotesSubscriber>", doc: "",
  });
  assert.deepEqual(arg("Notebook", "watch-title"), {
    name: "callback", index: 0, encoding: "function", params: ["title"], type: "(title: string) => void", doc: "",
  });
});

