// The `cf-os api` command generator: turns the schema `extract.ts` produces into the generated
// files, `src/api/generated/schema.json` and the command table `src/api/generated/commands.ts`.
//
// Pure, in the shape of a forge plugin: `generate(schema)` returns the files and touches nothing.
// No `node:` imports, no file system, clock or environment; `generate.ts` does the I/O. Every
// decision the CLI makes about a method -- its command name, which parameters are positional and
// which are flags, how each is encoded, what its result does to the chain -- is made here, once,
// and written into the table, so the runtime holds no per-method knowledge.

import type {
  ApiArg, ApiCallback, ApiCommand, ApiEncoding, ApiNode, ApiReturn, ApiShape, ApiTable,
} from "../src/api/table.ts";

/** What `extract.ts` produces: the capability graph reachable from the entry interface. */
export interface Schema {
  /** The entry interface's name (`PublicApi`): a key of `services`. */
  entry: string;
  /** Exported byte constants, by name. */
  constants: Record<string, number[]>;
  /** Every capability interface reached, server- and client-implemented alike, by name. */
  services: Record<string, SchemaService>;
  /** Named object and union types, by name, which `ref` shapes refer to. */
  shapes: Record<string, ApiShape>;
}

/** One capability interface. */
export interface SchemaService {
  doc: string;
  /** Its methods, inherited ones included, sorted by name. */
  methods: SchemaMethod[];
}

/** One method. */
export interface SchemaMethod {
  name: string;
  doc: string;
  params: SchemaParam[];
  /** The awaited result: a value's shape, or a `stub` naming the service it continues on. */
  returns: ApiShape;
}

/** One method parameter. */
export interface SchemaParam {
  name: string;
  /** Its type, `undefined` removed when `optional`. */
  type: ApiShape;
  optional: boolean;
  doc: string;
}

/** One generated file, its path relative to the `cf-os` package. */
export interface File {
  path: string;
  contents: string;
}

/** Where the generated files go, relative to the `cf-os` package. */
export const SCHEMA_PATH = "src/api/generated/schema.json";
export const COMMANDS_PATH = "src/api/generated/commands.ts";

const HEADER = "// Generated by packages/cf-os/generator/generate.ts from "
  + "cloudflare-os/packages/workshop-shared/src/api.ts; do not edit. Run pnpm api:generate.\n";

/**
 * `PublicApi`'s credential methods. The session performs them itself, from env or cloudflared, so
 * no secret ever comes from argv; they are not commands.
 */
export const CREDENTIAL_METHODS = ["authenticate", "authenticateFromCfAccess", "createAccount", "login"];

/**
 * The root's methods that take password hashes, which the CLI could only take from argv (or a file
 * written for the purpose): not commands either.
 */
export const ROOT_CREDENTIAL_METHODS = ["changePassword"];

/** The credential method whose result is the table's root. */
const AUTHENTICATE = "authenticate";

/** The segment selecting the public node. */
const PUBLIC = "public";

/**
 * Flags the runtime itself takes. An optional parameter whose flag would be one of these is
 * given as `--arg-<name>` instead.
 */
export const RESERVED_FLAGS = ["account", "auth", "config", "dry-run", "help", "out", "profile", "timeout", "url",
  "username"];

/** Every generated file for `schema`. */
export function generate(schema: Schema): File[] {
  return [
    { path: SCHEMA_PATH, contents: `${JSON.stringify(schema, null, 2)}\n` },
    { path: COMMANDS_PATH, contents: renderTable(buildTable(schema)) },
  ];
}

/** `getChatHistory` as `get-chat-history`, `amIAdmin` as `am-i-admin`. */
export function kebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").replace(/_/g, "-")
    .toLowerCase();
}

/** The command table for `schema`. Throws naming the methods behind any ambiguity. */
export function buildTable(schema: Schema): ApiTable {
  const publicService = service(schema, schema.entry, "the entry");
  const authenticate = publicService.methods.find((method) => method.name === AUTHENTICATE);
  const root = authenticate && deref(schema, authenticate.returns);
  if (root?.kind !== "stub" || !root.service) {
    throw new Error(`${schema.entry}.${AUTHENTICATE}() does not return a capability, so there is no root`);
  }
  const salt = schema.constants.SERVICE_SALT;
  if (!salt) throw new Error("no SERVICE_SALT constant");

  const nodes: Record<string, ApiNode> = {};
  const callbacks: Record<string, ApiCallback> = {};
  const queue = [root.service, schema.entry];
  while (queue.length > 0) {
    const name = queue.shift()!;
    if (nodes[name]) continue;
    const omitted = name === schema.entry ? CREDENTIAL_METHODS : name === root.service ? ROOT_CREDENTIAL_METHODS : [];
    const node = buildNode(schema, name, callbacks, omitted);
    nodes[name] = node;
    for (const command of Object.values(node.commands)) {
      if (command.returns.kind === "stub") queue.push(command.returns.node);
    }
  }
  if (nodes[root.service]!.commands[PUBLIC]) {
    throw new Error(`${root.service} has a method named "${PUBLIC}", which the CLI reserves for ${schema.entry}`);
  }

  const shapes: Record<string, ApiShape> = {};
  const pending = [...refs(Object.values(nodes).flatMap((node) =>
    Object.values(node.commands).flatMap((command) => command.args.map((arg) => arg.shape))))];
  while (pending.length > 0) {
    const name = pending.shift()!;
    if (shapes[name]) continue;
    const shape = schema.shapes[name];
    if (!shape) throw new Error(`no shape ${name}`);
    shapes[name] = shape;
    pending.push(...refs([shape]));
  }

  return {
    root: root.service,
    public: schema.entry,
    constants: { SERVICE_SALT: salt },
    nodes: sortRecord(nodes),
    callbacks: sortRecord(callbacks),
    shapes: sortRecord(shapes),
  };
}

function service(schema: Schema, name: string, what: string) {
  const found = schema.services[name];
  if (!found) throw new Error(`no service ${name} (${what})`);
  return found;
}

function buildNode(schema: Schema, name: string, callbacks: Record<string, ApiCallback>, omitted: string[]): ApiNode {
  const commands: Record<string, ApiCommand> = {};
  const methodOf: Record<string, string> = {};
  for (const method of service(schema, name, "a stub's").methods) {
    if (omitted.includes(method.name)) continue;
    const command = kebab(method.name);
    if (methodOf[command]) {
      throw new Error(`${name}.${methodOf[command]} and ${name}.${method.name} are both the command "${command}"`);
    }
    methodOf[command] = method.name;
    commands[command] = buildCommand(schema, `${name}.${method.name}`, method, callbacks);
  }
  return { doc: service(schema, name, "a stub's").doc, commands: sortRecord(commands) };
}

function buildCommand(schema: Schema, where: string, method: SchemaMethod,
  callbacks: Record<string, ApiCallback>): ApiCommand {
  const args: ApiArg[] = [];
  const paramOf: Record<string, string> = {};
  method.params.forEach((param, index) => {
    const arg = buildArg(schema, `${where}(${param.name})`, param, index, callbacks);
    if (!arg) return;
    if (arg.flag) {
      if (paramOf[arg.flag]) {
        throw new Error(`${where}: parameters ${paramOf[arg.flag]} and ${param.name} are both --${arg.flag}`);
      }
      paramOf[arg.flag] = param.name;
    }
    args.push(arg);
  });
  return { method: method.name, doc: method.doc, args, returns: buildReturn(schema, method, args) };
}

/** The parameter as an argument, or undefined for an optional callback, which is never passed. */
function buildArg(schema: Schema, where: string, param: SchemaParam, index: number,
  callbacks: Record<string, ApiCallback>): ApiArg | undefined {
  const base = { name: param.name, index };
  const tail = { type: typeText(param.type), doc: param.doc };
  const type = deref(schema, param.type);
  if (type.kind === "stub" || type.kind === "function") {
    if (param.optional) return undefined;
    if (type.kind === "function") {
      return { ...base, encoding: "function", params: type.params.map((p) => p.name), ...tail };
    }
    if (!type.service) throw new Error(`${where}: an untyped capability, which the CLI cannot implement`);
    callbacks[type.service] ??= buildCallback(service(schema, type.service, `${where}'s callback`));
    return { ...base, encoding: "callback", callback: type.service, ...tail };
  }
  if (type.kind === "writableStream") throw new Error(`${where}: a WritableStream, which the CLI cannot provide`);

  const flag = param.optional ? { flag: flagFor(param.name) } : {};
  const direct = scalar(schema, type);
  if (direct) return { ...base, ...flag, ...direct, ...tail };
  if (type.kind === "union") {
    const rest = type.branches.filter((branch) => branch.kind !== "null" && branch.kind !== "undefined");
    const inner = rest.length === 1 ? rest[0]! : { kind: "union" as const, branches: rest };
    const nullable = rest.length < type.branches.length ? scalar(schema, inner) : undefined;
    if (nullable && nullable.encoding !== "stream") {
      return {
        ...base, ...flag, ...nullable, ...(type.branches.some((b) => b.kind === "null") ? { nullable: true } : {}),
        ...tail,
      };
    }
  }
  return { ...base, ...flag, encoding: "json", shape: param.type, ...tail };
}

function flagFor(name: string): string {
  const flag = kebab(name);
  return RESERVED_FLAGS.includes(flag) ? `arg-${flag}` : flag;
}

/** A scalar encoding (with a string-literal union's choices), or undefined for JSON. */
function scalar(schema: Schema, shape: ApiShape): { encoding: ApiEncoding; choices?: string[] } | undefined {
  const type = deref(schema, shape);
  switch (type.kind) {
    case "string": case "number": case "boolean": case "bigint": case "date": case "bytes":
      return { encoding: type.kind };
    case "readableStream":
      return { encoding: "stream" };
    case "literal":
      return literals([type]);
    case "union":
      return literals(type.branches.map((branch) => deref(schema, branch)));
    default:
      return undefined;
  }
}

function literals(shapes: ApiShape[]): { encoding: ApiEncoding; choices?: string[] } | undefined {
  if (!shapes.every((shape) => shape.kind === "literal")) return undefined;
  const values = shapes.map((shape) => (shape as { value: string | number | boolean }).value);
  if (values.every((value) => typeof value === "string")) {
    return { encoding: "string", choices: values.toSorted() };
  }
  if (values.every((value) => typeof value === "number")) return { encoding: "number" };
  if (values.every((value) => typeof value === "boolean")) return { encoding: "boolean" };
  return undefined;
}

function buildReturn(schema: Schema, method: SchemaMethod, args: ApiArg[]): ApiReturn {
  if (args.some((arg) => arg.encoding === "callback" || arg.encoding === "function")) return { kind: "subscription" };
  let type = deref(schema, method.returns);
  let nullable = false;
  if (type.kind === "union") {
    const rest = type.branches.filter((branch) => branch.kind !== "null" && branch.kind !== "undefined");
    const only = rest.length === 1 ? deref(schema, rest[0]!) : undefined;
    if (only?.kind === "stub") {
      type = only;
      nullable = true;
    }
  }
  if (type.kind === "stub") {
    if (!type.service) return { kind: "untyped" };
    if (service(schema, type.service, `${method.name}'s result`).methods.length === 0) return { kind: "handle" };
    return { kind: "stub", node: type.service, nullable };
  }
  if (type.kind === "readableStream") return { kind: "stream" };
  return { kind: "value", type: typeText(method.returns) };
}

function buildCallback(callback: SchemaService): ApiCallback {
  return {
    doc: callback.doc,
    methods: callback.methods.map((method) => ({
      name: method.name,
      params: method.params.map((param) => param.name),
      doc: method.doc,
    })).toSorted((a, b) => compare(a.name, b.name)),
  };
}

/** A `ref`'s shape; anything else as it is. */
function deref(schema: Schema, shape: ApiShape): ApiShape {
  const seen = new Set<string>();
  while (shape.kind === "ref" && !seen.has(shape.name)) {
    seen.add(shape.name);
    const target = schema.shapes[shape.name];
    if (!target) throw new Error(`no shape ${shape.name}`);
    shape = target;
  }
  return shape;
}

/** The names every `ref` inside `values` refers to. */
function refs(values: unknown[]): Set<string> {
  const names = new Set<string>();
  const walk = (value: unknown): void => {
    if (Array.isArray(value)) value.forEach(walk);
    else if (value && typeof value === "object") {
      const record = value as Record<string, unknown>;
      if (record.kind === "ref" && typeof record.name === "string") names.add(record.name);
      Object.values(record).forEach(walk);
    }
  };
  values.forEach(walk);
  return names;
}

function sortRecord<T>(record: Record<string, T>): Record<string, T> {
  return Object.fromEntries(Object.entries(record).toSorted(([a], [b]) => compare(a, b)));
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

const BUILTIN_TEXT: Record<string, string> = {
  date: "Date", bytes: "Uint8Array", error: "Error", readableStream: "ReadableStream",
  writableStream: "WritableStream", arrayBuffer: "ArrayBuffer", dataView: "DataView", regexp: "RegExp",
  blob: "Blob", url: "URL", headers: "Headers", request: "Request", response: "Response",
};

/** A shape as TypeScript-like text, for help: named shapes by name. */
export function typeText(shape: ApiShape): string {
  switch (shape.kind) {
    case "literal": return JSON.stringify(shape.value);
    case "array": return `${wrapped(shape.element)}[]`;
    case "set": return `Set<${typeText(shape.element)}>`;
    case "map": return `Map<${typeText(shape.key)}, ${typeText(shape.value)}>`;
    case "tuple": {
      const min = shape.minLength ?? shape.elements.length;
      const elements = shape.elements.map((element, i) => `${typeText(element)}${i < min ? "" : "?"}`);
      if (shape.rest) elements.push(`...${wrapped(shape.rest)}[]`);
      return `[${elements.join(", ")}]`;
    }
    case "object": {
      const entries = Object.entries(shape.properties).map(([key, value]) => {
        const optional = value.kind === "undefined"
          || value.kind === "union" && value.branches.some((branch) => branch.kind === "undefined");
        const inner = value.kind === "union" && optional ? withoutUndefined(value) : value;
        return `${propertyKey(key)}${optional ? "?" : ""}: ${typeText(inner)}`;
      });
      if (shape.index && entries.length === 0) return `Record<string, ${typeText(shape.index)}>`;
      if (shape.index) entries.push(`[key: string]: ${typeText(shape.index)}`);
      return entries.length === 0 ? "{}" : `{ ${entries.join("; ")} }`;
    }
    case "union": {
      return shape.branches.toSorted((a, b) => nullishLast(a) - nullishLast(b)).map(wrapped).join(" | ");
    }
    case "ref": return shape.name;
    case "typedArray": return shape.name;
    case "stub": return `RpcStub<${shape.service ?? "any"}>`;
    case "function": {
      const params = shape.params.map((p) => `${p.name}${p.optional ? "?" : ""}: ${typeText(p.type)}`);
      return `(${params.join(", ")}) => ${typeText(shape.returns)}`;
    }
    case "unsupported": return "unknown";
    default: return BUILTIN_TEXT[shape.kind] ?? shape.kind;
  }
}

/** Sorts `null`, then `undefined`, after the other branches, as TypeScript is written. */
function nullishLast(shape: ApiShape): number {
  return shape.kind === "null" ? 1 : shape.kind === "undefined" ? 2 : 0;
}

function wrapped(shape: ApiShape): string {
  return shape.kind === "union" || shape.kind === "function" ? `(${typeText(shape)})` : typeText(shape);
}

function withoutUndefined(shape: ApiShape & { kind: "union" }): ApiShape {
  const branches = shape.branches.filter((branch) => branch.kind !== "undefined");
  return branches.length === 1 ? branches[0]! : { kind: "union", branches };
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function propertyKey(key: string): string {
  return IDENTIFIER.test(key) ? key : JSON.stringify(key);
}

const WIDTH = 110;

/** `commands.ts`: the header, the type import, and the table as one readable literal. */
export function renderTable(table: ApiTable): string {
  return `${HEADER}\nimport type { ApiTable } from "../table.ts";\n\n`
    + `/** The \`cf-os api\` command table: every command the pinned upstream API offers. */\n`
    + `export const table: ApiTable = ${literal(table, "", "export const table: ApiTable = ".length)};\n`;
}

/**
 * A JSON-like value as a TypeScript literal: inline when it fits the line, one entry per line
 * otherwise, and a long multi-line string as one `+`-joined line per source line.
 */
function literal(value: unknown, indent: string, used: number): string {
  const inline = inlineLiteral(value);
  if (inline !== undefined && used + inline.length <= WIDTH) return inline;
  const inner = `${indent}  `;
  if (typeof value === "string") {
    const lines = value.split(/(?<=\n)/);
    if (lines.length === 1) return JSON.stringify(value);
    return `\n${lines.map((line) => `${inner}${JSON.stringify(line)}`).join(" +\n")}`;
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((item) => `${inner}${literal(item, inner, inner.length)},`).join("\n")}\n${indent}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, item]) => item !== undefined);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([key, item]) => {
    const head = `${inner}${propertyKey(key)}: `;
    const text = literal(item, inner, head.length);
    // A multi-line string starts on the next line.
    return text.startsWith("\n") ? `${head.trimEnd()}${text},` : `${head}${text},`;
  }).join("\n")}\n${indent}}`;
}

/** The value on one line, or undefined when it holds a multi-line string. */
function inlineLiteral(value: unknown): string | undefined {
  if (typeof value === "string") return value.includes("\n") ? undefined : JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    const items = value.map(inlineLiteral);
    return items.includes(undefined) ? undefined : `[${items.join(", ")}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value).filter(([, item]) => item !== undefined);
    if (entries.length === 0) return "{}";
    const items = entries.map(([key, item]) => {
      const text = inlineLiteral(item);
      return text === undefined ? undefined : `${propertyKey(key)}: ${text}`;
    });
    return items.includes(undefined) ? undefined : `{ ${items.join(", ")} }`;
  }
  return JSON.stringify(value);
}

/** One command, for diffs and listings. */
export interface CommandEntry {
  /** Its segments, space-joined from the root (`open-gadget get-chat-history`, `public ping`). */
  path: string;
  /**
   * Every path that reaches it, {@link path} among them, no capability visited twice
   * (`new-gadget get-chat-history` too). A diff matches commands by these, so a hop added to a
   * capability that is already reachable moves none of its commands.
   */
  routes: string[];
  /** Its signature: arguments, result and callbacks, with every named shape they reach. */
  signature: string;
}

/**
 * Every command of `schema`'s table, keyed by its path. Each node's commands are listed under one
 * path, the shortest from the root (or `public`), preferring hops that get or open an existing
 * capability (`open-gadget`) over ones that create one (`new-gadget`); the others are its routes.
 */
export function commandEntries(schema: Schema): Map<string, CommandEntry> {
  const table = buildTable(schema);
  const prefixes = new Map<string, string[]>([[table.root, []]]);
  const queue = [table.root, table.public];
  prefixes.set(table.public, [PUBLIC]);
  for (let i = 0; i < queue.length; i++) {
    const node = queue[i]!;
    const prefix = prefixes.get(node)!;
    const hops = Object.entries(table.nodes[node]!.commands)
      .toSorted(([a], [b]) => hopRank(a) - hopRank(b) || compare(a, b));
    for (const [name, command] of hops) {
      if (command.returns.kind !== "stub" || prefixes.has(command.returns.node)) continue;
      prefixes.set(command.returns.node, [...prefix, name]);
      queue.push(command.returns.node);
    }
  }

  const routes = new Map<string, string[][]>();
  const walk = (node: string, prefix: string[], visited: Set<string>) => {
    routes.set(node, [...routes.get(node) ?? [], prefix]);
    for (const [name, command] of Object.entries(table.nodes[node]!.commands)) {
      if (command.returns.kind !== "stub" || visited.has(command.returns.node)) continue;
      walk(command.returns.node, [...prefix, name], new Set([...visited, command.returns.node]));
    }
  };
  walk(table.root, [], new Set([table.root]));
  walk(table.public, [PUBLIC], new Set([table.public]));

  const entries = new Map<string, CommandEntry>();
  for (const node of queue) {
    const methods = new Map(schema.services[node]!.methods.map((method) => [method.name, method]));
    for (const [name, command] of Object.entries(table.nodes[node]!.commands)) {
      const method = methods.get(command.method)!;
      // Without the help text (`doc`, and `type`, which prints interface names): the shapes say it.
      const { type: _type, ...returns } = command.returns as ApiReturn & { type?: string };
      const local = {
        args: command.args.map(({ doc, type, ...arg }) => arg),
        returns,
        params: method.params.map(({ type, optional }) => ({ type, optional })),
        result: method.returns,
        // What the server may call back: a method it gains or a changed parameter is a change.
        callbacks: command.args.flatMap((arg) => arg.callback ? [schema.services[arg.callback]!.methods.map(
          ({ name: callbackName, params }) => ({ name: callbackName, params: params.map(({ type, optional }) =>
            ({ type, optional })) }))] : []),
      };
      const reached = [...reachable(schema, refs([local]))].toSorted()
        .map((shape) => `${shape}=${JSON.stringify(schema.shapes[shape] ?? null)}`);
      const path = [...prefixes.get(node)!, name].join(" ");
      entries.set(path, {
        path,
        routes: routes.get(node)!.map((prefix) => [...prefix, name].join(" ")).toSorted(compare),
        signature: JSON.stringify({ local, shapes: reached }, withoutInterfaceNames),
      });
    }
  }
  return entries;
}

/**
 * Leaves out which interface a capability or callback is: that is the path's business. Renaming one
 * upstream moves no command, and one that truly replaces it shows in the commands under it.
 */
function withoutInterfaceNames(key: string, value: unknown): unknown {
  return INTERFACE_NAME_KEYS.has(key) && typeof value === "string" ? undefined : value;
}

/** The keys of table and schema entries whose value names an interface. */
const INTERFACE_NAME_KEYS = new Set(["node", "service", "callback"]);

/** Hops that get or open an existing capability first. */
function hopRank(command: string): number {
  return /^(get|open)-/.test(command) ? 0 : 1;
}

/** The named shapes `names` reach, themselves included. */
function reachable(schema: Schema, names: Set<string>): Set<string> {
  const found = new Set<string>();
  const pending = [...names];
  while (pending.length > 0) {
    const name = pending.pop()!;
    if (found.has(name)) continue;
    found.add(name);
    const shape = schema.shapes[name];
    if (shape) pending.push(...refs([shape]));
  }
  return found;
}

function sorted(paths: string[]): string[] {
  return paths.toSorted(compare);
}

/** What changed between two schemas' commands. Each list holds command paths, sorted. */
export interface CommandDiff {
  added: string[];
  removed: string[];
  /** The same command with different arguments or result. */
  changed: string[];
}

/** The commands `after` adds, removes and changes relative to `before` (none: all added). */
export function diffCommands(before: Schema | undefined, after: Schema): CommandDiff {
  const old = [...(before ? commandEntries(before) : new Map<string, CommandEntry>()).values()];
  const now = [...commandEntries(after).values()];
  const byRoute = (entries: CommandEntry[]) => new Map(entries.flatMap((entry) => entry.routes.map((route) => [route, entry])));
  const oldByRoute = byRoute(old);
  const nowByRoute = byRoute(now);
  /** The same command on the other side: one reached there by any of the same paths. */
  const counterpart = (entry: CommandEntry, other: Map<string, CommandEntry>) =>
    entry.routes.map((route) => other.get(route)).find((found) => found !== undefined);
  return {
    added: sorted(now.filter((entry) => !counterpart(entry, oldByRoute)).map((entry) => entry.path)),
    removed: sorted(old.filter((entry) => !counterpart(entry, nowByRoute)).map((entry) => entry.path)),
    changed: sorted(now.filter((entry) => {
      const was = counterpart(entry, oldByRoute);
      return was !== undefined && was.signature !== entry.signature;
    }).map((entry) => entry.path)),
  };
}
